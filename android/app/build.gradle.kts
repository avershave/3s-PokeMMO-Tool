// The overlay data is generated by the Node scripts and not committed; fail early with a clear message.
val checkOverlayAssets by tasks.registering {
    val tagsFile = file("src/main/assets/overlay/tags.json")
    doLast {
        if (!tagsFile.exists()) {
            throw GradleException("Overlay assets are missing. Run `npm run overlay:build` first.")
        }
    }
}
tasks.matching { it.name == "preBuild" }.configureEach { dependsOn(checkOverlayAssets) }
